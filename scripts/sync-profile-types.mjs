// Keep one public language surface while preserving profile-local augmentation.
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const source = await readFile(new URL('../packages/compat-cordis/index.d.ts',import.meta.url),'utf8');
const output = '// Generated by scripts/sync-profile-types.mjs; edit the common Cordis declarations.\n' + source
  .replace("constructor(options?: { addon?: string; profile?: 'cordis' | 'harness' });", 'constructor(options?: { addon?: string });')
  .replace('update(config: any, noSave?: boolean): Awaitable<void>;', 'update(config: any, noSave?: boolean): void;');
const target = new URL('../packages/compat-harness/index.d.ts',import.meta.url);
if (process.argv.includes('--check')) assert.equal(await readFile(target,'utf8'),output,'Harness declarations are stale; run node scripts/sync-profile-types.mjs');
else await writeFile(target,output);
