import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {HostBridge} from '../../packages/compat-cordis/host-bridge.js';
const native=createRequire(import.meta.url)('../../packages/compat-cordis/native/cordis.node');

test('R2 acceptance: dynamic publication, retained object, failed cleanup and stale retry',()=>{
  const driver=new native.NativeDriver(), host=new HostBridge(driver);
  const command=request=>JSON.parse(driver.command(JSON.stringify(request)));
  const port={key:'41',realm:'9'};
  const mount=(dependencies=[],parent=null)=>{
    const {id}=command({op:'mount',dependencies,provisions:[],parent});
    const fiber={id};host.bind(id,fiber);return fiber;
  };
  const check=()=>{driver.validateHostSnapshot();return command({op:'snapshot'});};
  const provider=mount();
  let action=command({op:'drive'}).actions.find(a=>a.id===provider.id);
  const providerGeneration=action.ticket.generation;
  const setup=host.begin(action.ticket,provider,{kind:'provider',revision:1});
  const old={version:1},replacement={version:2};
  const published=host.publish({op:'publish',id:provider.id,generation:action.ticket.generation,...port},old);
  host.complete(setup,true);
  const consumer=mount([port],provider.id);
  action=command({op:'drive'}).actions.find(a=>a.id===consumer.id);
  const generation=action.ticket.generation;
  const call=host.begin(action.ticket,consumer,{kind:'consumer',revision:1});
  const read=()=>host.resolve({op:'resolve',...port,consumer:consumer.id,generation});
  assert.strictEqual(read().value,old);
  host.complete(call,true);check();
  host.publish({op:'set',id:provider.id,generation:providerGeneration,publication:published.publication},replacement);
  assert.strictEqual(read().value,replacement);check();
  command({op:'retire',id:provider.id});
  action=command({op:'drive'}).actions.find(a=>a.kind==='cleanup'&&a.id===consumer.id);
  assert(action,'consumer cleanup must precede provider cleanup');
  const cleanup=host.begin(action.ticket,consumer,{kind:'cleanup',revision:1});
  assert.strictEqual(read().value,replacement);
  host.complete(cleanup,false,'injected inverse failure');
  let state=check();
  assert(state.plugins.find(p=>p.id===consumer.id).cleanupFailed);
  assert(!command({op:'drive'}).actions.some(a=>a.kind==='cleanup'&&a.id===provider.id));
  assert.strictEqual(read().value,replacement);
  const retry=command({op:'retry_cleanup',id:consumer.id}).actions[0];
  assert.notDeepEqual(retry.ticket,action.ticket);
  const second=host.begin(retry.ticket,consumer,{kind:'cleanup',revision:2});
  const before=check();
  assert.throws(()=>host.complete(cleanup,true),/Stale/);
  assert.deepEqual(check(),before,'old completion must not consume the new action');
  assert.strictEqual(host.recipe(second).revision,2);
  host.complete(second,true);check();
  let actions=command({op:'drive'}).actions;
  const release=actions.find(a=>a.kind==='cleanup'&&a.id===provider.id);
  assert(release,'provider becomes releasable after consumer succeeds');
  const last=host.begin(release.ticket,provider,{kind:'cleanup',revision:1});
  host.complete(last,true);
  for(let i=0;i<4;i++)command({op:'drive'});
  state=check();assert.equal(state.plugins.length,0);
  host.unbind(consumer.id);host.unbind(provider.id);check();
});
